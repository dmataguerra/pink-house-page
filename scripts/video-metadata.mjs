import { mkdirSync, statSync, writeFileSync } from 'node:fs';

const videoByteLength = statSync(new URL('../public/videos/pink-house.mp4', import.meta.url)).size;
if (videoByteLength > 25 * 1024 * 1024) {
  throw new Error('The MP4 exceeds the Cloudflare Pages limit of 25 MiB per asset.');
}
const directory = new URL('../cloudflare/', import.meta.url);
mkdirSync(directory, { recursive: true });
writeFileSync(new URL('video-metadata.js', directory),
  `// Generated by scripts/video-metadata.mjs from the original MP4.\nexport const videoByteLength = ${videoByteLength};\n`);
